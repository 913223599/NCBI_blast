_GENUS_TO_PHYLUM: Dict[str, str] = {
    genus: phylum
    for phylum, genera in _PHYLUM_GENERA.items()
    for genus in genera
}


def map_host_to_phylum(host: Optional[str]) -> str:
    """将宿主描述/属名规范化映射为细菌门（Phylum）或 Archaea / Others；未知宿主返回空串。"""
    raw = (host or "").strip()
    if raw.lower() in _UNKNOWN_TOKENS:
        return ""
    tokens = [tok.strip("[](),;") for tok in raw.split() if tok.strip("[](),;")]
    if not tokens:
        return ""
    target = tokens[1].lower() if tokens[0].lower() == "candidatus" and len(tokens) > 1 else tokens[0].lower()
    if target in _UNKNOWN_TOKENS:
        return ""
    return _GENUS_TO_PHYLUM.get(target, "Others")


def get_host_group_color(group: str) -> str:
    """返回宿主分类群对应的稳定发表配色。"""
    return HOST_GROUP_COLORS.get(group, "#6b7280")
